// 仅补「正面管教标签体系」（8 能力分类 + 关注 + 70 标签）。用于老库迁移：已有学生/记录时只补分类标签，不覆盖数据。
// 🔴 幂等：分类按空库灌；标签按【名称去重】补，避免重复灌，也保留旧库残留标签（无害）。
export async function seedTaxonomy(db) {
  if (!(await db.categories.count())) await bulkPutCategories(db, CATEGORIES_SEED.map(c => ({ ...c })));
  const existing = new Set((await db.tags.toArray()).map(t => t.name));
  const toAdd = TAGS_SEED.filter(t => !existing.has(t.name));
  if (toAdd.length) await bulkPutTags(db, toAdd.map(t => ({ ...t })));
}

// 首装基线：只补「功能性内容」——标签体系 + 空白课表 + 默认分类。**不含任何学生 / 记录 / 临时数据**。
// 老师打开就是干净的空班级，自己录名单、自己排课。
export async function seedBaseline(db) {
  await seedTaxonomy(db);
  if (!(await getSchedule(db))) await saveSchedule(db, BLANK_SCHEDULE);
  const cur = await getSetting('defaultCat', null);
  if (!cur) await setSetting('defaultCat', WUYU[0]);
}
